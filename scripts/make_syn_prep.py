"""Kaggle CPU kernel that builds the PF-syn training set (scripts/prep_syn_data.py) from the outputs of GLACIER
simulation worker kernels (scripts/make_sim_workers.py) -> /kaggle/working/<out>.npz.

python scripts/make_syn_prep.py <slug> <jobs_dataset> <structs.parquet name> <pool_dataset> <out name> <worker slug> [...]
e.g. python scripts/make_syn_prep.py casmi26-syn-prep2 casmi26-sim-jobs2 sim2_structs.parquet casmi26-pool-v18c syn2 \
       casmi26-simw2-0 ... casmi26-simw2-23
The pool dataset must be the one the structures file indexes (pid); prep_syn_data matches every prediction back to its
pool id by InChIKey14 and prints the matched share. The simulation files are passed in sorted order (deterministic
output); the kernel log lists them with their sizes.
"""
import json, os, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
slug, jobs_ds, structs, pool_ds, out = sys.argv[1:6]
workers = sys.argv[6:]
NB = f'''"""PF-syn data build (scripts/prep_syn_data.py, generated by scripts/make_syn_prep.py): GLACIER-simulated [M+H]+
spectra (CE 20 / 40 / 60 eV) from the worker kernels {workers[0]} ... {workers[-1]} ({len(workers)}) for the structures of
bryantyu/{jobs_ds}/{structs}, pool bryantyu/{pool_ds} -> /kaggle/working/{out}.npz."""
import glob, os, shutil, subprocess, sys
tag = f'cp{{sys.version_info.major}}{{sys.version_info.minor}}'
whl = [w for w in glob.glob('/kaggle/input/**/rdkit-2026.3.3-*.whl', recursive=True) if tag in w]
subprocess.run([sys.executable, '-m', 'pip', 'install', '-q', '--no-index', '--no-deps', whl[0]], check=True)
first = lambda pat: sorted(glob.glob(f'/kaggle/input/**/{{pat}}', recursive=True), key=len)[0]
shutil.copytree(os.path.dirname(first('peakformer.py')), '/kaggle/working/pkg/casmi', dirs_exist_ok=True)
sims = sorted(glob.glob('/kaggle/input/**/*.sim.npz', recursive=True), key=os.path.basename)
print(len(sims), 'simulation files', flush=True)
for f in sims:
    print(' ', os.path.basename(f), os.path.getsize(f), flush=True)
subprocess.run('free -g; nproc', shell=True)
r = subprocess.run([sys.executable, '/kaggle/working/pkg/casmi/prep_syn_data_script.py', first({structs!r}), first('fpx.npz'),
                    '/kaggle/working/{out}.npz'] + sims, env={{**os.environ, 'POOL': first('pool.parquet'), 'RICHFP_CACHE': '/none',
                    'PREP_PROCS': '4', 'PYTHONPATH': '/kaggle/working/pkg'}}, text=True)
print('exit', r.returncode, flush=True)
subprocess.run('md5sum /kaggle/working/{out}.npz; free -g', shell=True)
shutil.rmtree('/kaggle/working/pkg', ignore_errors=True)
'''
d = os.path.join(root, 'kernels', slug)
os.makedirs(d, exist_ok=True)
open(os.path.join(d, 'notebook.py'), 'w').write(NB)
json.dump({'id': f'bryantyu/{slug}', 'title': slug, 'code_file': 'notebook.py', 'language': 'python', 'kernel_type': 'script',
           'is_private': True, 'enable_gpu': False, 'enable_tpu': False, 'enable_internet': False,
           'dataset_sources': ['bryantyu/casmi26-code', f'bryantyu/{jobs_ds}', 'bryantyu/casmi26-pf-data', f'bryantyu/{pool_ds}',
                               'metric/rdkit-2026-3-3-wheel'],
           'competition_sources': [], 'kernel_sources': [f'bryantyu/{w}' for w in workers], 'model_sources': []},
          open(os.path.join(d, 'kernel-metadata.json'), 'w'), indent=2)
print('wrote', d, len(workers), 'worker sources')
